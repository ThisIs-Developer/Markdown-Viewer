import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Commit this small browser/worker bundle so static hosting needs no npm runtime.
await build({
  entryPoints: [fileURLToPath(new URL('../src/document-toc.mjs', import.meta.url))],
  outfile: fileURLToPath(new URL('../assets/document-toc.js', import.meta.url)),
  bundle: true,
  format: 'iife',
  globalName: 'MarkdownDocumentToc',
  target: 'es2020',
  // Keep Markdown hard breaks escaped instead of literal trailing whitespace.
  supported: { 'template-literal': false },
  minify: true,
  banner: { js: '/* Generated by npm run build:toc. Source: src/document-toc.mjs. Licenses: document-toc.LICENSE.txt. */' },
  legalComments: 'none',
});
const licenses = await Promise.all(['github-slugger', 'entities'].map(async name =>
  name + '\n\n' + await readFile(new URL('../node_modules/' + name + '/LICENSE', import.meta.url), 'utf8')));
await writeFile(new URL('../assets/document-toc.LICENSE.txt', import.meta.url), licenses.join('\n\n'));
