const localeLookup = new Map(SEO_LOCALES.map(locale => [locale.code, locale]));

export function getSeoLocale(code) {
  return localeLookup.get(String(code || '').toLowerCase()) || localeLookup.get('en');
}

export function hasSeoLocale(code) {
  return localeLookup.has(String(code || '').toLowerCase());
}

export function canonicalPathForLocale(localeOrCode) {
  const locale = typeof localeOrCode === 'string' ? getSeoLocale(localeOrCode) : localeOrCode;
  return locale.code === 'en' ? '/' : `/?lang=${encodeURIComponent(locale.code)}`;
}

export function canonicalUrlForLocale(localeOrCode) {
  return `${SITE_ORIGIN}${canonicalPathForLocale(localeOrCode)}`;
}

export function hreflangEntries() {
  return [
    { hreflang: 'x-default', href: `${SITE_ORIGIN}/` },
    ...SEO_LOCALES.map(locale => ({
      hreflang: locale.hreflang,
      href: canonicalUrlForLocale(locale)
    }))
  ];
}
